<?php

namespace Tests\Feature;

use App\Helpers\FileEncrypt;
use App\Models\Catalog;
use App\Models\Config;
use App\Models\Lock;
use App\Notifications\BackupFailedNotification;
use App\Notifications\BackupFinishedNotification;
use Illuminate\Database\Connection;
use Illuminate\Notifications\AnonymousNotifiable;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Notification;
use Symfony\Component\Yaml\Yaml;
use Tests\Concerns\FakesMysqldump;
use Tests\TestCase;

/**
 * Requires a MySQL/MariaDB server, mysqldump is replaced by a fake executable.
 */
class BackupCommandTest extends TestCase
{
    use FakesMysqldump;

    protected const DUMP_FILE = __DIR__.'/../Fixtures/dump.sql';

    protected const STDERR_WARNING = 'WARNING: this line must not reach the snapshot';

    protected const VIEWS_DATABASE = 'mybackup_views_test';

    protected function setUp(): void
    {
        parent::setUp();
        Notification::fake();
    }

    public function test_compressed_backup(): void
    {
        $dir = $this->makeBackupPlan(['compress' => true]);

        $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertOk();

        $this->assertEquals(['catalog.sqlite', 'config.yaml', 'snapshot.sql.gz'], $this->files($dir));

        $content = file_get_contents('compress.zlib://'.$dir.'snapshot.sql.gz');
        $this->assertStringContainsString(file_get_contents(static::DUMP_FILE), $content);
        $this->assertStringNotContainsString(static::STDERR_WARNING, $content);

        $this->assertEquals(realpath($dir.'snapshot.sql.gz'), Catalog::query()->value('snapshot'));
        $this->assertFalse(Lock::hasLock());
        Notification::assertSentOnDemand(BackupFinishedNotification::class);
        Notification::assertNotSentTo(new AnonymousNotifiable, BackupFailedNotification::class);
    }

    public function test_encrypted_backup_does_not_keep_unencrypted_snapshot(): void
    {
        $dir = $this->makeBackupPlan([
            'compress' => true,
            'encryption' => ['key' => 'secret'],
        ]);

        $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertOk();

        $this->assertEquals(['catalog.sqlite', 'config.yaml', 'snapshot.sql.gz.aes'], $this->files($dir));

        FileEncrypt::decrypt($dir.'snapshot.sql.gz.aes', $dir.'decrypted.sql.gz', 'secret');
        $this->assertStringContainsString(
            file_get_contents(static::DUMP_FILE),
            file_get_contents('compress.zlib://'.$dir.'decrypted.sql.gz')
        );
    }

    public function test_backup_adds_begin_and_end_text(): void
    {
        $dir = $this->makeBackupPlan([
            'dump' => [
                'begin' => ['SET SESSION sql_log_bin=0;', 'SET SESSION rocksdb_bulk_load=1;'],
                'end' => '-- File generated by MyBackup',
            ],
        ]);

        $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertOk();

        $content = file_get_contents($dir.'snapshot.sql');
        $this->assertStringStartsWith("SET SESSION sql_log_bin=0;\nSET SESSION rocksdb_bulk_load=1;\n\n", $content);
        $this->assertStringContainsString(file_get_contents(static::DUMP_FILE), $content);
        $this->assertStringEndsWith("\n\n-- File generated by MyBackup\n", $content);
    }

    public function test_failed_backup_removes_partial_snapshot_and_notifies(): void
    {
        $dir = $this->makeBackupPlan(['compress' => true], 2);

        $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertFailed();

        $this->assertEquals(['catalog.sqlite', 'config.yaml'], $this->files($dir));
        $this->assertEquals(0, Catalog::query()->count());
        $this->assertFalse(Lock::hasLock());

        Notification::assertSentOnDemand(
            BackupFailedNotification::class,
            fn (BackupFailedNotification $notification) => str_contains($notification->toSlack(null)->content, 'Unable to perform backup')
        );
    }

    public function test_backup_fails_when_locked_by_running_process(): void
    {
        $dir = $this->makeBackupPlan();
        $this->artisan('unlock', ['config_file' => $dir.'config.yaml'])->assertOk();
        Lock::create(['pid' => getmypid(), 'hostname' => gethostname()]);

        $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertFailed();

        $this->assertTrue(Lock::hasLock());
        $this->assertEquals(['catalog.sqlite', 'config.yaml'], $this->files($dir));
        Notification::assertSentOnDemand(BackupFailedNotification::class);
    }

    public function test_backup_removes_stale_lock(): void
    {
        $dir = $this->makeBackupPlan();
        $this->artisan('unlock', ['config_file' => $dir.'config.yaml'])->assertOk();

        $process = proc_open(['true'], [], $pipes);
        Lock::create(['pid' => proc_get_status($process)['pid'], 'hostname' => gethostname()]);
        proc_close($process);

        $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertOk();

        $this->assertFalse(Lock::hasLock());
        $this->assertEquals(['catalog.sqlite', 'config.yaml', 'snapshot.sql'], $this->files($dir));
    }

    public function test_backup_dumps_views_after_tables(): void
    {
        $this->createViewsDatabase();

        try {
            $dir = $this->makeBackupPlan([
                // Output the received arguments instead of a dump
                'mysqldump_path' => $this->fakeMysqldump('echo "$@"'),
                'databases' => [[static::VIEWS_DATABASE => ['tables' => ['v_top', 'orders', 'v_totals']]]],
            ]);

            $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertOk();

            $commands = array_values(array_filter(explode("\n", file_get_contents($dir.'snapshot.sql'))));
            $this->assertCount(2, $commands);
            $this->assertStringEndsWith(static::VIEWS_DATABASE.' orders', $commands[0]);
            $this->assertStringEndsWith(static::VIEWS_DATABASE.' v_top v_totals', $commands[1]);
        } finally {
            $this->targetConnection()->statement('DROP DATABASE IF EXISTS '.static::VIEWS_DATABASE);
        }
    }

    public function test_backup_dumps_only_struct_tables_without_data(): void
    {
        $dir = $this->makeBackupPlan([
            // Output the received arguments instead of a dump
            'mysqldump_path' => $this->fakeMysqldump('echo "$@"'),
            'databases' => [['mybackup_test' => ['tables' => [
                ['orders' => ['where' => 'id > 1']],
                ['logs' => ['where' => 'id > 1', 'only_struct' => true]],
            ]]]],
        ]);

        $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertOk();

        $commands = array_values(array_filter(explode("\n", file_get_contents($dir.'snapshot.sql'))));
        $this->assertCount(2, $commands);
        $this->assertStringEndsWith('--where=id > 1 mybackup_test orders', $commands[0]);
        $this->assertStringEndsWith('--no-data mybackup_test logs', $commands[1]);
    }

    /**
     * Uses the real mariadb-dump, so the views are restored into an empty database.
     */
    public function test_views_restore_in_any_order(): void
    {
        $mariadbDump = trim((string) shell_exec('command -v mariadb-dump'));

        if (! $mariadbDump) {
            $this->markTestSkipped('mariadb-dump is not available');
        }

        $this->createViewsDatabase();

        try {
            $dir = $this->makeBackupPlan([
                'mysqldump_path' => $mariadbDump,
                'databases' => [[static::VIEWS_DATABASE => [
                    // Table dumps don't select the database
                    'to' => static::VIEWS_DATABASE,
                    'tables' => ['v_top', 'orders', 'v_totals'],
                ]]],
            ]);

            $this->artisan('backup', ['config_file' => $dir.'config.yaml'])->assertOk();

            $connection = $this->targetConnection();
            $connection->statement('DROP DATABASE '.static::VIEWS_DATABASE);
            $connection->statement('CREATE DATABASE '.static::VIEWS_DATABASE);

            $this->artisan('restore', [
                '--config_file' => $dir.'config.yaml',
                'backup_file' => $dir.'snapshot.sql',
            ])->assertOk();

            $this->assertEquals(
                ['ana' => 30],
                collect($connection->select('SELECT * FROM '.static::VIEWS_DATABASE.'.v_top'))->pluck('total', 'customer')->all()
            );
        } finally {
            $this->targetConnection()->statement('DROP DATABASE IF EXISTS '.static::VIEWS_DATABASE);
        }
    }

    /**
     * Create a database with a view that depends on a table and a view that depends on another view.
     */
    protected function createViewsDatabase(): void
    {
        $db = static::VIEWS_DATABASE;
        $connection = $this->targetConnection();

        $connection->statement("DROP DATABASE IF EXISTS $db");
        $connection->statement("CREATE DATABASE $db");
        $connection->statement("CREATE TABLE $db.orders (id INT PRIMARY KEY, customer VARCHAR(20), amount INT)");
        $connection->statement("INSERT INTO $db.orders VALUES (1, 'ana', 10), (2, 'ana', 20), (3, 'bob', 5)");
        $connection->statement("CREATE VIEW $db.v_totals AS SELECT customer, SUM(amount) AS total FROM $db.orders GROUP BY customer");
        $connection->statement("CREATE VIEW $db.v_top AS SELECT customer, total FROM $db.v_totals WHERE total > 10");
    }

    /**
     * Connection to the test server.
     */
    protected function targetConnection(): Connection
    {
        config(['database.connections.target' => array_merge(
            config('database.connections.target'),
            ['host' => '127.0.0.1', 'username' => 'root', 'password' => '']
        )]);

        return DB::connection('target');
    }

    /**
     * Create a backup plan into a new directory.
     */
    protected function makeBackupPlan(array $config = [], int $mysqldumpExitCode = 0): string
    {
        $dir = static::$tmpDir.uniqid().'/';
        mkdir($dir);

        $config = array_merge(
            Config::generateConfig('Backup test', $dir.'catalog.sqlite', $dir.'snapshot.sql'),
            [
                'mysqldump_path' => $this->fakeMysqldump(
                    $this->dumpScript(static::DUMP_FILE, static::STDERR_WARNING, $mysqldumpExitCode)
                ),
                'databases' => ['mybackup_test'],
                'notifications' => ['slack' => ['webhook' => 'https://hooks.slack.com/services/test']],
            ],
            $config
        );

        $config['connection']['host'] = '127.0.0.1';
        file_put_contents($dir.'config.yaml', Yaml::dump($config));

        return $dir;
    }

    /**
     * List the files of a directory.
     */
    protected function files(string $dir): array
    {
        return array_values(array_diff(scandir($dir), ['.', '..']));
    }
}
